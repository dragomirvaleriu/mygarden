// Overlays the English translation (if one exists for this id) on top of
// the RO base entry. Falls back to the RO strings for any id not yet
// translated, so a missing translation degrades to Romanian text rather
// than a runtime crash or a blank field.
export function getLocalizedPlant(plant: PlantCatalogEntry, lang: string): PlantCatalogEntry {
  if (lang !== 'en') return plant;
  const translation = plantCatalogEn[plant.id];
  return translation ? { ...plant, ...translation } : plant;
}

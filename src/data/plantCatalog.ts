// Broader grouping than `type` (interior/exterior) — added once the catalog
// grew past ~25 entries mixing houseplants, annuals, shrubs, trees and
// groundcover, at which point "exterior" alone stopped being a useful way
// to browse. Kept as a plain string union rather than a shared const array
// so it type-checks against typos at the call site.
export type PlantCategory =
  | 'plante-interior'
  | 'flori-anuale'
  | 'flori-perene-arbusti'
  | 'flori-bulboase'
  | 'copaci-ornamentali'
  | 'acoperitoare-sol'
  | 'aromatice-legume'
  | 'gazon';

export type PlantHeight = 'mic' | 'mediu' | 'mare';
export type PlantWaterNeed = 'redusa' | 'medie' | 'abundenta';
export type PlantLightNeed = 'umbra' | 'semi-umbra' | 'soare';

export interface PlantCatalogEntry {
  id: string;
  name: string;
  scientificName: string;
  emoji: string;
  type: 'interior' | 'exterior';
  category: PlantCategory;
  // Coarse buckets (not exact cm/L) so every entry can be filled in
  // confidently from a plant's general profile, and so the Explore filters
  // stay simple three-way toggles instead of a numeric range picker.
  heightCategory: PlantHeight;
  waterNeed: PlantWaterNeed;
  lightNeed: PlantLightNeed;
  difficulty: 'ușor' | 'mediu' | 'dificil';
  watering: string;
  light: string;
  description: string;
  tags: string[];
  // Richer fields, added once the catalog needed to be a genuine reference,
  // not a 3-line card. Every entry fills all of these — kept as required
  // strings (not optional) so a missing field is a compile error, not a
  // silently-blank section in the UI.
  origin: string;
  soil: string;
  bloomTime: string;
  fertilizing: string;
  maintenance: string;
  commonProblems: string;
  propagation: string;
}

